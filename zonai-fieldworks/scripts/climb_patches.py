"""Emit Phantom Foothold's climbing edits for Fieldworks and check their hook windows."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

MOD = Path(__file__).resolve().parents[1]
ROOT = MOD.parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "mods/code/phantom-foothold/scripts"))

import game_profiles as phantom  # noqa: E402
from totk_version_port import VERSIONS, image  # noqa: E402

HEADER = MOD / "src/fieldworks/generated/ClimbPatches.hpp"
WINDOW_WORDS = 5


def patches(version: str) -> list[tuple[int, int, int]]:
    rows = []
    for index, offset in enumerate(phantom.PATCH_OFFSETS[version]):
        if offset is None:
            continue
        original = phantom.original(version, index)
        rows.append((offset, original, phantom.replacement(version, index, original)))
    return sorted(rows)


def branch_targets(words: np.ndarray) -> np.ndarray:
    w = words.astype(np.int64)
    site = np.arange(len(w), dtype=np.int64) * 4

    def signed(value: np.ndarray, bits: int) -> np.ndarray:
        return np.where(value & (1 << (bits - 1)), value - (1 << bits), value)

    found = []
    b = (w & 0x7C000000) == 0x14000000  # B, BL
    found.append(site[b] + 4 * signed(w[b] & 0x3FFFFFF, 26))
    for mask, value in ((0xFF000010, 0x54000000), (0x7E000000, 0x34000000)):  # B.cond, CBZ/CBNZ
        m = (w & mask) == value
        found.append(site[m] + 4 * signed((w[m] >> 5) & 0x7FFFF, 19))
    t = (w & 0x7E000000) == 0x36000000  # TBZ/TBNZ
    found.append(site[t] + 4 * signed((w[t] >> 5) & 0x3FFF, 14))
    a = (w & 0x9F000000) == 0x10000000  # ADR
    imm = ((w[a] >> 29) & 3) | (((w[a] >> 5) & 0x7FFFF) << 2)
    found.append(site[a] + signed(imm, 21))
    return np.unique(np.concatenate(found))


def check_version(version: str) -> tuple[list[str], int]:
    native = image(version)
    failures = []
    rows = patches(version)
    for offset, original, _ in rows:
        found = native.word(offset)
        if found != original:
            failures.append(f"{version} @{offset:08X}: expected {original:08X}, found {found:08X}")
    targets = branch_targets(native.words)
    unsafe = 0
    for offset, _, _ in rows:
        lo = np.searchsorted(targets, offset + 4)
        hi = np.searchsorted(targets, offset + 4 * WINDOW_WORDS)
        unsafe += int(hi > lo)
    return failures, unsafe


def render() -> bytes:
    lines = [
        "// GENERATED by mods/code/zonai-fieldworks/scripts/climb_patches.py --write; do not edit.",
        "// Source: mods/code/phantom-foothold/scripts/game_profiles.py.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace fieldworks::climb {",
        "struct Patch {",
        "    std::uint32_t offset, original, replacement;",
        "};",
        "struct VersionPatches {",
        "    const char* version;",
        "    std::uint32_t count;",
        "    Patch patches[17];",
        "};",
        "inline constexpr VersionPatches kVersions[] = {",
    ]
    for version in VERSIONS:
        rows = patches(version)
        body = ", ".join(f"{{0x{o:08X}, 0x{a:08X}, 0x{b:08X}}}" for o, a, b in rows)
        lines.append(f'    {{"{version}", {len(rows)}, {{{body}}}}},')
    lines += ["};", "}  // namespace fieldworks::climb", ""]
    return "\n".join(lines).encode("ascii")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write the generated header")
    args = parser.parse_args()
    failures = []
    unsafe = 0
    for version in VERSIONS:
        found, wide = check_version(version)
        failures += found
        unsafe += wide
    for failure in failures:
        print(failure)
    if failures:
        raise SystemExit(f"{len(failures)} climbing-edit check failures")
    expected = render()
    if args.write:
        HEADER.parent.mkdir(parents=True, exist_ok=True)
        HEADER.write_bytes(expected)
    if not HEADER.exists() or HEADER.read_bytes().replace(b"\r\n", b"\n") != expected:
        raise SystemExit(f"generated header differs: {HEADER}")
    total = sum(len(patches(v)) for v in VERSIONS)
    print(f"Verified {total} climbing edits on {len(VERSIONS)} versions; a {WINDOW_WORDS}-word hook "
          f"would break {unsafe} of them, so only one-word hooks are installed")


if __name__ == "__main__":
    main()
