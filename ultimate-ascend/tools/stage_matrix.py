"""Stage exact validated matrix payloads and version-specific capture manifests."""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tomllib
from pathlib import Path

from native_profile_data import VERSIONS


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--matrix',type=Path,required=True)
    args=p.parse_args()
    mod=Path(__file__).resolve().parents[1]
    metadata=tomllib.loads((mod/'mod.toml').read_text())
    version=metadata['mod']['version']
    stage_ledger=metadata['evidence']['stage_ledger']
    profiles=mod/'profiles';profiles.mkdir(exist_ok=True)
    summary=[]
    for game in VERSIONS:
        for variant in ('standard','restricted'):
            folder=args.matrix/game/variant
            row=json.loads((folder/'matrix-entry.json').read_text())
            report=json.loads((folder/'base/report.json').read_text())
            validation=json.loads((folder/'base/validated.json').read_text())
            composition=json.loads((folder/'combined/composition.json').read_text())
            compatibility=json.loads((folder/'combined/compatibility.json').read_text())
            if (row['version']!=game or row['variant']!=variant or validation['research_only']
                    or composition.get('research_only',False) or compatibility['initializer']!='pass'
                    or compatibility['upward_differential_cases']!=56
                    or compatibility['downward_bypass_cases']!=4
                    or compatibility['shrine_vanilla_cases']!=(56 if variant=='restricted' else 0)
                    or bool(report.get('shrine_gates'))!=(variant=='restricted')):
                raise ValueError(f'Incomplete matrix entry: {game}/{variant}')
            if row['payload_sha256'] != composition['payload_sha256']:
                raise ValueError('Matrix entry and composition disagree')
            staged=mod/'build-matrix'/game/variant
            staged.mkdir(parents=True,exist_ok=True)
            for name,digest in row['payload_sha256'].items():
                source=folder/'combined'/name
                if hashlib.sha256(source.read_bytes()).hexdigest()!=digest:
                    raise ValueError(f'Payload changed: {source}')
                shutil.copyfile(source,staged/name)
            shutil.copyfile(folder/'matrix-entry.json',staged/'validation-summary.json')
            addon='ultimate-ascend'+('-shrine-restricted' if variant=='restricted' else '')
            title='Ultimate Ascend'+(' (Shrine Restricted)' if variant=='restricted' else '')
            ips=next(n for n in row['payload_sha256'] if n.endswith('.ips'))
            relative=staged.relative_to(mod).as_posix()
            patch=f'ultimate-ascend-v{game.replace(".","")}.pchtxt'
            manifest=f'''# Generated by tools/stage_matrix.py; one exact game build per capture.
[mod]
id = "ultimate-ascend"
display_name = "{title}"
version = "{version}"
totk_version = "{game}"
build_id = "{report['build_id']}"

[build]
target = "payload"
directory = "{relative}"

[evidence]
source_roots = ["scripts/patch_gaps", "scripts/totk_version_port", "scripts/nso_decompress.py"]
stage_ledger = "{stage_ledger}"

[[payload.file]]
source = "{relative}/ultimate-ascend.pchtxt"
dest = "exefs/{patch}"

[[payload.file]]
source = "{relative}/{ips}"
dest = "exefs_patches/{addon}/{ips}"

[deploy]
addon = "{addon}"
migrated = true
shared_restbl = false

[conflicts]
subsdk_slots = []
'''
            (profiles/f'v{game.replace(".","")}-{variant}.toml').write_text(manifest,encoding='utf-8')
            summary.append(row)
    target=mod/'build-matrix/validated-matrix.json'
    target.write_text(json.dumps(dict(results=summary,observed=False),indent=2)+'\n')
    print(json.dumps(dict(versions=len(VERSIONS),variants=2,payloads=len(summary),summary=str(target))))


if __name__=='__main__':
    main()
